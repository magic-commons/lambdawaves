#!/usr/bin/env node
/* tools/state-scopes.mjs — ONE STORE (021 R4): writes docs/STATE-SCOPES.md's "The records" table from lab/settings-store.js RECORDS, the
 * registry of every key λWAVES keeps on this device ({ key, scope, version, forget, owner }), between the two markers below; the rest of
 * the file is prose and stays hand-written.  The catalogue-table precedent:
 *   node tools/state-scopes.mjs           write the table into docs/STATE-SCOPES.md
 *   node tools/state-scopes.mjs --check   write nothing; exit 1 unless the file is byte for byte what this writes (./test.sh node runs it) */
import { readFileSync, writeFileSync } from 'node:fs';
import { RECORDS, WORKSPACE, RETIRED } from '../lab/settings-store.js';

const DOC = new URL('../docs/STATE-SCOPES.md', import.meta.url), BEGIN = '<!-- state-scopes:begin (generated by tools/state-scopes.mjs from lab/settings-store.js; do not edit) -->', END = '<!-- state-scopes:end -->';
const cell = (s) => String(s).replace(/\|/g, '\\|');
const table = [BEGIN, '', '## The records (generated)', '',
  'Every key this device keeps, one row each (`lab/settings-store.js` RECORDS). FORGET (MIR OPTIONS) wipes the rows marked yes; `kit ·` rows are',
  'the kit\'s own, listed so nothing is unnamed. The settings blob\'s WORKSPACE keys: ' + WORKSPACE.map((k) => '`' + k + '`').join(', ') + '; every other blob key is',
  'PREFERENCE. RETIRED blob keys, dropped by the next save: ' + RETIRED.map((k) => '`' + k + '`').join(', ') + '.', '',
  '| key | scope | version | FORGET | owner |', '|---|---|---|---|---|',
  ...RECORDS.map((r) => `| \`${r.key}${r.prefix ? '*' : ''}\` | ${r.scope} | ${cell(r.version)} | ${r.forget ? 'yes' : 'no'} | ${cell(r.owner)} |`),
  '', END].join('\n');
const text = readFileSync(DOC, 'utf8'), a = text.indexOf(BEGIN), b = text.indexOf(END);
const at = text.indexOf('## The table');
const out = a >= 0 && b > a ? text.slice(0, a) + table + text.slice(b + END.length) : text.slice(0, at) + table + '\n\n' + text.slice(at);
if (process.argv.includes('--check')) {
  if (out !== text) { console.error('docs/STATE-SCOPES.md is not what tools/state-scopes.mjs writes from lab/settings-store.js — run `node tools/state-scopes.mjs`'); process.exit(1); }
  console.log(`PASS docs/STATE-SCOPES.md's records table is the registry's (${RECORDS.length} rows)`);
} else { writeFileSync(DOC, out); console.log(`wrote docs/STATE-SCOPES.md's records table (${RECORDS.length} rows, ${table.split('\n').length} lines)`); }
